//go:build windows && arm64

#include "textflag.h"

// The test of the floating point registers: see fp_arm64.go.

#define SENTINEL(n) $(0x4000000000000000+n)

TEXT ·fpProbeAddr(SB), NOSPLIT, $0-8
	MOVD $·fpProbe(SB), R0
	MOVD R0, ret+0(FP)
	RET

// Go code is free to change F8-F15: this does.
TEXT ·clobberFP(SB), NOSPLIT, $0-0
	MOVD $0x7ff0000000000001, R10
	FMOVD R10, F8
	FMOVD R10, F9
	FMOVD R10, F10
	FMOVD R10, F11
	FMOVD R10, F12
	FMOVD R10, F13
	FMOVD R10, F14
	FMOVD R10, F15
	RET

// uintptr fpProbe(f uintptr): a C function, called by syscall.SyscallN.
TEXT ·fpProbe(SB), NOSPLIT|NOFRAME, $0
	SUB   $144, RSP
	MOVD  LR, 128(RSP)
	FSTPD (F8, F9), 0(RSP)
	FSTPD (F10, F11), 16(RSP)
	FSTPD (F12, F13), 32(RSP)
	FSTPD (F14, F15), 48(RSP)
	MOVD  SENTINEL(8), R10
	FMOVD R10, F8
	MOVD  SENTINEL(9), R10
	FMOVD R10, F9
	MOVD  SENTINEL(10), R10
	FMOVD R10, F10
	MOVD  SENTINEL(11), R10
	FMOVD R10, F11
	MOVD  SENTINEL(12), R10
	FMOVD R10, F12
	MOVD  SENTINEL(13), R10
	FMOVD R10, F13
	MOVD  SENTINEL(14), R10
	FMOVD R10, F14
	MOVD  SENTINEL(15), R10
	FMOVD R10, F15
	MOVD  R0, R10
	BL    (R10)
	MOVD  $0, R9
	FMOVD F8, R11
	MOVD  SENTINEL(8), R12
	CMP   R12, R11
	CSET  NE, R13
	ORR   R13<<0, R9
	FMOVD F9, R11
	MOVD  SENTINEL(9), R12
	CMP   R12, R11
	CSET  NE, R13
	ORR   R13<<1, R9
	FMOVD F10, R11
	MOVD  SENTINEL(10), R12
	CMP   R12, R11
	CSET  NE, R13
	ORR   R13<<2, R9
	FMOVD F11, R11
	MOVD  SENTINEL(11), R12
	CMP   R12, R11
	CSET  NE, R13
	ORR   R13<<3, R9
	FMOVD F12, R11
	MOVD  SENTINEL(12), R12
	CMP   R12, R11
	CSET  NE, R13
	ORR   R13<<4, R9
	FMOVD F13, R11
	MOVD  SENTINEL(13), R12
	CMP   R12, R11
	CSET  NE, R13
	ORR   R13<<5, R9
	FMOVD F14, R11
	MOVD  SENTINEL(14), R12
	CMP   R12, R11
	CSET  NE, R13
	ORR   R13<<6, R9
	FMOVD F15, R11
	MOVD  SENTINEL(15), R12
	CMP   R12, R11
	CSET  NE, R13
	ORR   R13<<7, R9
	MOVD  R9, R0
	FLDPD 0(RSP), (F8, F9)
	FLDPD 16(RSP), (F10, F11)
	FLDPD 32(RSP), (F12, F13)
	FLDPD 48(RSP), (F14, F15)
	MOVD  128(RSP), LR
	ADD   $144, RSP
	RET
